const FIELD_LABELS = {
  eventName: "اسم الفعالية أو البرنامج",
  organizer: "الجهة المنظمة داخل الكلية",
  date: "تاريخ التنفيذ",
  location: "مكان التنفيذ",
  audience: "الفئة المستهدفة",
  presenter: "مقدم البرنامج أو المحاضر",
  topics: "أبرز محاور البرنامج",
  objectives: "الأهداف",
  highlights: "أبرز ما تم خلال الفعالية",
  extra: "معلومات إضافية",
};

export function buildGenerateUserMessage(input, previous) {
  const lines = [];
  for (const [key, label] of Object.entries(FIELD_LABELS)) {
    const v = (input[key] || "").trim();
    if (v) lines.push(`${label}: ${v}`);
  }
  const free = (input.freeText || "").trim();
  let msg = "البيانات المدخلة عن الفعالية:\n";
  if (lines.length) msg += lines.join("\n") + "\n";
  if (free) msg += `\nملخص حر من المستخدم:\n${free}\n`;
  if (!lines.length && !free) msg += "(لا توجد بيانات)\n";
  if (previous?.ar_body) {
    msg += `\nملاحظة: هذه إعادة توليد. الصياغة السابقة لم تُعجب المستخدم، فاكتب صياغة مختلفة في البناء والمفردات مع الالتزام بالمعلومات نفسها.\nالعنوان السابق: ${previous.ar_title}\n`;
  }
  return msg;
}

export function buildTranslateUserMessage({ ar_title, ar_body, prev_en_title, prev_en_body }) {
  let msg = `العنوان العربي الحالي:\n${ar_title}\n\nالنص العربي الحالي:\n${ar_body}\n`;
  if (prev_en_body) {
    msg += `\nالنسخة الإنجليزية السابقة (قبل التعديل):\nTitle: ${prev_en_title || ""}\n${prev_en_body}\n`;
  }
  return msg;
}

export function buildAltTextContext({ eventName, organizer, ar_title, date, location }) {
  const parts = [`الكلية: ${COLLEGE_AR} – ${UNIVERSITY_AR}`];
  if (ar_title) parts.push(`عنوان الخبر: ${ar_title}`);
  if (eventName) parts.push(`اسم الفعالية: ${eventName}`);
  if (organizer) parts.push(`الجهة المنظمة: ${organizer}`);
  if (date) parts.push(`التاريخ: ${date}`);
  if (location) parts.push(`المكان: ${location}`);
  return parts.join("\n");
}
